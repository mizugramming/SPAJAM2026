"""Generate small Claude Code entrypoints; keep skill bodies in .agents/skills.

Uses the standard library only. Default/--check never writes. --write updates
only files marked as generated, and refuses symlinks or unowned destinations.
"""

import argparse
import json
from pathlib import Path
import tempfile

from check_skills import contained, metadata


MARKER = "<!-- Generated by tool/sync_claude_skills.py; edit the shared skill. -->"


def entrypoint(source: Path) -> str:
    fields = metadata(source)
    name = fields["name"]
    description = json.dumps(fields["description"], ensure_ascii=False)
    return (
        f"---\nname: {name}\ndescription: {description}\n---\n\n"
        f"{MARKER}\n\n"
        f"[共有Skillの本文](../../../.agents/skills/{name}/SKILL.md) を先に読み、"
        "その手順で依頼を進める。本文内の相対参照は、共有Skillの配置場所を"
        "基準に解決する。\n"
    )


def synchronize(root: Path, write: bool = False) -> int:
    root = root.resolve()
    sources = sorted((root / ".agents/skills").glob("*/SKILL.md"))
    if not sources:
        raise ValueError("no shared skills found")
    instructions = root / "CLAUDE.md"
    if (not instructions.is_file()
            or "@AGENTS.md" not in instructions.read_text(encoding="utf-8").splitlines()
            or not (root / "AGENTS.md").is_file()):
        raise ValueError("CLAUDE.md must import the existing @AGENTS.md")

    expected = {}
    for source in sources:
        contained(root, str(source.relative_to(root)))
        destination = root / ".claude/skills" / source.parent.name / "SKILL.md"
        expected[destination] = entrypoint(source)
    problems, updates = [], []
    for destination, content in expected.items():
        # Refuse even an internal symlink: Windows clones need real files, and
        # a later link change must never redirect writes into user settings.
        parents = (root / ".claude", destination.parent.parent,
                   destination.parent, destination)
        if any(path.is_symlink() for path in parents):
            problems.append(f"refusing symlink: {destination.relative_to(root)}")
            continue
        if any(path.exists() and not path.is_dir() for path in parents[:-1]):
            problems.append(f"parent is not a directory: {destination.relative_to(root)}")
            continue
        contained(root, str(destination.relative_to(root)))
        if destination.exists() and not destination.is_file():
            problems.append(f"not a regular file: {destination.relative_to(root)}")
            continue
        previous = (destination.read_text(encoding="utf-8")
                    if destination.exists() else None)
        if previous == content:
            continue
        if previous is not None and MARKER not in previous.splitlines():
            problems.append(f"preserving unowned file: {destination.relative_to(root)}")
        elif write:
            updates.append((destination, content))
        else:
            problems.append(f"missing or stale entrypoint: {destination.relative_to(root)}")

    directory = root / ".claude/skills"
    if not directory.is_symlink():
        for candidate in sorted(directory.glob("*/SKILL.md")):
            if candidate in expected or candidate.is_symlink() or candidate.parent.is_symlink():
                continue
            if MARKER in candidate.read_text(encoding="utf-8").splitlines():
                problems.append(f"obsolete generated entrypoint; inspect before removing: "
                                f"{candidate.relative_to(root)}")
    if problems:
        raise ValueError("\n".join(problems))
    # Preflight every destination before writing any of them.
    for destination, content in updates:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")
    return len(updates)


def self_test() -> None:
    with tempfile.TemporaryDirectory(prefix="spajam-claude-entrypoints-") as temporary:
        root = Path(temporary) / "repo"
        source = root / ".agents/skills/example/SKILL.md"
        source.parent.mkdir(parents=True)
        original = "---\nname: example\ndescription: Focused shared workflow.\n---\n"
        source.write_text(original + "\nRead [guide](references/guide.md).\n", encoding="utf-8")
        guide = source.parent / "references/guide.md"
        guide.parent.mkdir()
        guide.write_text("A source-relative reference.\n", encoding="utf-8")
        (root / "AGENTS.md").write_text("Shared rules.\n", encoding="utf-8")
        (root / "CLAUDE.md").write_text("@AGENTS.md\n", encoding="utf-8")
        target = root / ".claude/skills/example/SKILL.md"

        def rejected(label: str, fragment: str, write: bool = False) -> None:
            try:
                synchronize(root, write=write)
            except ValueError as error:
                assert fragment in str(error), str(error)
                print(f"PASS: {label}")
            else:
                raise AssertionError(f"{label}: invalid bundle was accepted")

        rejected("missing Claude entrypoint detected", "missing or stale")
        canonical = source.read_bytes()
        assert synchronize(root, write=True) == 1
        assert synchronize(root) == 0
        assert source.read_bytes() == canonical
        assert not (target.parent / "references").exists()
        link = contained(root, str((target.parent / "../../../.agents/skills/example/SKILL.md")
                                   .relative_to(root)))
        assert link == source
        print("PASS: generated entrypoint resolves to unchanged shared instructions")
        assert synchronize(root, write=True) == 0
        print("PASS: repeated generation changes nothing")
        source.write_text(source.read_text().replace("Focused shared", "Updated shared"),
                          encoding="utf-8")
        rejected("description drift detected", "missing or stale")
        assert synchronize(root, write=True) == 1
        target.write_text("A developer-owned skill.\n", encoding="utf-8")
        rejected("developer-owned entrypoint preserved", "preserving unowned", write=True)
        assert target.read_text() == "A developer-owned skill.\n"
        target.unlink()
        target.parent.rmdir()
        target.parent.write_text("A developer-owned path.\n", encoding="utf-8")
        rejected("occupied parent path preserved", "parent is not a directory", write=True)
        assert target.parent.read_text() == "A developer-owned path.\n"
        target.parent.unlink()
        target.parent.mkdir()
        target.write_text(entrypoint(source), encoding="utf-8")
        source.unlink()
        second = root / ".agents/skills/other/SKILL.md"
        second.parent.mkdir()
        second.write_text("---\nname: other\ndescription: Another task.\n---\n",
                          encoding="utf-8")
        rejected("obsolete entrypoint detected without deletion", "obsolete generated", write=True)
        assert target.exists()
        target.unlink()
        target.parent.rmdir()
        outside = Path(temporary) / "outside"
        outside.mkdir()
        try:
            target.parent.symlink_to(outside, target_is_directory=True)
        except OSError:
            print("SKIP: symlink refusal (OS did not permit creating a test link)")
        else:
            source.write_text(original, encoding="utf-8")
            rejected("symlink destination refused", "refusing symlink", write=True)
            assert not list(outside.iterdir())
            target.parent.unlink()
        (root / "CLAUDE.md").write_text("Read AGENTS.md.\n", encoding="utf-8")
        rejected("missing instruction import detected", "must import")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="verify without writing (default)")
    modes.add_argument("--write", action="store_true", help="refresh generated entrypoints")
    modes.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        else:
            changed = synchronize(args.root, write=args.write)
            print(f"PASS: Claude entrypoints match shared skills ({changed} updated)")
    except (OSError, ValueError) as error:
        print(error)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
